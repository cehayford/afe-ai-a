	<span class="kicker">Legal</span>
	<h1>Privacy notice</h1>
	<p class="notice small">
		Version 2026-09. Afe's lawyers are reviewing this notice before launch, and we will register with Ghana's Data
		Protection Commission before we take any personal data from the public.
	</p>

	<p class="lede">
		Afe helps renters in Accra find homes without getting scammed. To do that we check who landlords are, visit their
		homes, and hold rent safely until you move in. This notice says what that means for your personal data, under the
		Data Protection Act, 2012 (Act 843).
	</p>

	<h2>What we collect</h2>
	<ul>
		<li><strong>Your account:</strong> name, phone number, email if you give it, and how you use Afe (renter, landlord or agent).</li>
		<li><strong>Landlords and agents:</strong> the result of a Ghana Card check through our identity partner. We keep a
			scrambled code of the card number, not the number itself, so we can spot one card used on two accounts. The selfie
			for the check goes to the partner; Afe doesn't keep it. We also keep ownership or
			authority documents, and notes and photos from our verifier's visit.</li>
		<li><strong>Messages and viewings</strong> you send on Afe. We check message wording for common scams, such as asking for money before
			a viewing.</li>
		<li><strong>Payments:</strong> amounts and references from our payment partner. Card and mobile money details go to the partner,
			never to Afe.</li>
		<li><strong>Your device:</strong> a random ID in a cookie, the kind of browser you use, and your internet address. We use them to keep
			your account safe, limit abuse, and link accounts that may belong to the same person.</li>
		<li><strong>Verifiers on a visit:</strong> location while checking in and taking photos at a home.</li>
	</ul>

	<h2>Why we use it</h2>
	<ul>
		<li>To verify landlords and homes, and show renters what we checked.</li>
		<li>To detect and stop fraud, including scam reports from the public.</li>
		<li>To hold and release rent through our payment partner, and to settle disputes.</li>
		<li>To send you the messages you need (sign-in codes, viewings, payments) and the alerts you ask for.</li>
		<li>To meet our legal duties, such as keeping financial records.</li>
	</ul>

	<h2>Automated checks</h2>
	<p>
		Afe uses rules and computer models to spot possible scams, for example a rent far below the area or a photo used for
		another home. They never reject you, close your account, or hold your money on their own. They only ask an Afe
		reviewer to look. Every decision about you is made by a person, and you can appeal it once, to a different reviewer,
		from your account.
	</p>

	<h2>Who sees it</h2>
	<ul>
		<li>Afe staff who need it for their job. Every time a reviewer opens a private document, it's recorded.</li>
		<li>Our identity partner, payment partner, SMS, WhatsApp and email providers, and our cloud host, only to provide their
			service to us.</li>
		<li>The other person in a viewing, tenancy or dispute, only what they need (for example, your name).</li>
		<li>The police or a court, when the law requires it.</li>
	</ul>
	<p>Some of these providers keep data outside Ghana. We only use providers who protect it to the standard Act 843 requires.</p>

	<h2>How long we keep it</h2>
	<p>
		While your account is open. When you close it, we remove your profile, contact details, saved homes, notifications
		and message text. We keep payment and tenancy records, verification decisions, and the scrambled code of your Ghana Card
		for as long as the law and fraud prevention require. They are kept under a reference, not your name.
	</p>

	<h2>Your rights</h2>
	<ul>
		<li><strong>See your data:</strong> download everything we hold from your account page.</li>
		<li><strong>Correct it:</strong> change your details on your account page, or ask us.</li>
		<li><strong>Close your account</strong> from your account page, unless a tenancy is in progress or a fraud review is open.</li>
		<li><strong>Object or complain:</strong> write to us, or complain to the Data Protection Commission.</li>
	</ul>

	<p class="small muted">Afe will publish its contact address for privacy questions here before launch.</p>
