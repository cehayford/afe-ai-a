	<h1>Terms of use</h1>
	<p class="notice small">Version 2026-09. Afe's lawyers are reviewing these terms before launch.</p>

	<h2>What Afe does, and doesn't</h2>
	<p>
		Afe lists only homes whose landlord and home we have checked. We check the landlord's Ghana Card, see ownership or
		authority documents, and visit the home. A verification is a record of what we checked and when. It isn't a promise
		about the condition of a home or the conduct of a person.
	</p>

	<h2>For everyone</h2>
	<ul>
		<li>Never pay before you view. Afe never asks for a viewing fee.</li>
		<li>Use your own name and phone number. One person, one account.</li>
		<li>Don't use Afe to deceive anyone, harass anyone, or collect other people's details.</li>
		<li>Tell us about scams through "Check before you pay". We may suspend accounts while we look into a report.</li>
	</ul>

	<h2>For landlords and agents</h2>
	<ul>
		<li>List only homes you own or are authorised in writing to let, and keep your listing accurate.</li>
		<li>Advance rent must follow the Rent Act, 1963 (Act 220). Afe won't hold more than the law allows.</li>
		<li>Don't ask renters to pay outside Afe for a tenancy that started on Afe.</li>
		<li>Photos on verified listings are taken by Afe. You may not reuse another home's photos.</li>
	</ul>

	<h2>Protected payments</h2>
	<p>
		When protected payments are open, rent is held by Afe's licensed payment partner, not by Afe or the landlord. It is
		released when the tenant confirms they have moved in, or through the dispute and move-in rules shown on each tenancy.
		If a home isn't handed over, the tenant is refunded. Outside the launch offer, the payment partner's charges are
		taken from the refund.
	</p>

	<h2>Charges</h2>
	<p>
		During the launch offer, Afe's charges are free until 5 June 2027: verification, the protection fee, featured listings
		and landlord plans. We will give at least 30 days' notice before any charge starts. Prices are shown before you pay.
	</p>

	<h2>Decisions and appeals</h2>
	<p>
		Afe reviewers decide verifications, reports and disputes, and write down why. You can appeal a decision about you once,
		to a different reviewer, from your account.
	</p>

	<h2>Changes</h2>
	<p>If these terms change in a way that matters, we'll tell you and ask you to accept them again.</p>
